#!/usr/bin/env python3
"""Start a talking-head edit project (non-destructive intake).

  python3 scripts/edit_init.py /path/to/my-cut.mp4 --slug my-video [--fps 30] [--fit cover] [--app remotion-app] [--work work]
  python3 scripts/edit_init.py --script-only --slug my-video --duration 42.5 [--fps 30]   # no footage yet
  python3 scripts/edit_init.py /path/to/my-cut.mp4 --slug my-video                       # later: attach the cut

What it does (nothing is ever written to or next to the original):
  1. probes the ALREADY-CUT footage: resolution, rotation, frame rate (and VFR), duration, audio;
  2. records its sha256 so every later step can prove it is untouched;
  3. links it into the Remotion app (public/projects/<slug>/footage -> the original's folder; no copy);
  4. writes work/<slug>/project.json (the manifest), the project document edit.json (transcript, segments,
     concepts, decisions, beats, sound, approvals: the single source of truth), and the Remotion project
     src/projects/<slug>/: source.ts (GENERATED, timeline facts), beats.ts (the beat list you edit),
     concepts.ts (Creative Director concepts A/B/C/D for preview renders), sound-preview.ts (GENERATED later),
     Edit.tsx and index.tsx (the composition Edit-<slug>), and the creative decision log (edit_decisions.py);
  5. regenerates src/projects/index.tsx so the composition shows up in Remotion Studio.

The composition is exactly as long as the source (round(duration * fps) frames) at the approved
frame rate, 1080x1920. The approved frame rate defaults to the source's constant frame rate; a
variable-frame-rate source needs an explicit --fps. A non-9:16 source needs --fit cover (centre crop),
which must be approved by the user first. Re-running is safe: existing beats.ts/Edit.tsx are kept.

A script-only project has no footage yet: its timeline length is --duration (at least the end of the
user's script) at --fps (default 30). The Player shows a neutral stand-in instead of the face, previews
render without dialogue, and the final export and sound design are refused until the real cut is
attached by running edit_init.py again with the footage and the same --slug (decisions are kept).
"""
import argparse
import datetime
import json
import os
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import vedit as V  # noqa: E402

SOURCE_TS = """// GENERATED by the video-editing skill (edit_init.py) from the original footage.
// Do not edit by hand: these are the timeline facts every render is checked against.
import type {{ SourceInfo }} from "../../kit/types";

export const SOURCE: SourceInfo = {{
  src: {src},
  sourceWidth: {sw},
  sourceHeight: {sh},
  sourceFps: {sfps},
  sourceDurationSeconds: {dur},
  fps: {fps},
  durationInFrames: {frames},
  width: 1080,
  height: 1920,{extra}
}};

export const SOURCE_SHA256 = "{sha}";
"""

BEATS_TS = """// Approved timeline of "{slug}", read from edit.json (the single project file used by
// the Creative Director Studio, the Remotion Player and the renderers). Edit edit.json
// (in the Studio or with the skill's scripts), not this file.
// The footage itself is never cut, trimmed, re-timed or re-ordered (see SourceFootage).
import type {{ FocusWindow }} from "../../kit/SourceFootage";
import type {{ EditDoc }} from "../../kit/project";
import type {{ KitBeat }} from "../../kit/timing";
import EDIT from "./edit.json";

const DOC = EDIT as unknown as EditDoc;

/** Seconds where the hook ends: System D resolves the first riser into the body here (null = none). */
export const HOOK_END: number | null = DOC.hookEnd;

export const BEATS: KitBeat[] = DOC.beats as KitBeat[];

/** Optional dim/blur of the footage behind busy System A overlays (look only, never timing). */
export const FOCUS: FocusWindow[] = DOC.focus;

/** The Creative Director's constants: 60-30-10 palette and camera (read by useEditStyle()). */
export const CONSTANTS = DOC.constants;
"""

SOUND_TS = """// GENERATED by edit_render.py sound-preview from the mixer's session.json (Studio preview only).
import type { SoundPreviewData } from "../../kit/SoundPreview";

export const SOUND_PREVIEW: SoundPreviewData | null = null;
"""

EDIT_TSX = """import React from "react";
import {{ ConceptPick, selectBeats }} from "../../kit/concepts";
import {{ EditLayers, TalkingHeadEdit }} from "../../kit/TalkingHeadEdit";
import {{ BEATS, CONSTANTS, FOCUS }} from "./beats";
import {{ CONCEPTS }} from "./concepts";
import {{ SOUND_PREVIEW }} from "./sound-preview";
import {{ SOURCE }} from "./source";

// Talking-head edit "{slug}": untouched source footage + designed beats.
// `concept` renders one proposed concept (concepts.ts) instead of the approved
// beats, for Creative Director preview frames and motion previews.
// Project-specific components go here (pass them as extraComponents and
// their pure timing as extraTiming from ./timing.ts).
export const Edit: React.FC<{{ layers: EditLayers; concept: ConceptPick }}> = ({{ layers, concept }}) => (
  <TalkingHeadEdit
    source={{SOURCE}}
    beats={{selectBeats(BEATS, CONCEPTS, concept)}}
    focus={{concept ? [] : FOCUS}}
    sound={{concept ? null : SOUND_PREVIEW}}
    layers={{layers}}
    constants={{CONSTANTS}}
  />
);
"""

CONCEPTS_TS = """// Proposed A/B/C concepts of "{slug}" (Creative Director workflow), derived from edit.json:
// each visual concept becomes a renderable beat placed on its segment, for preview frames
// and motion previews. The options are presented by Claude / the Studio, not by Remotion.
import type {{ ConceptBeat }} from "../../kit/concepts";
import type {{ EditDoc }} from "../../kit/project";
import {{ beatFromConcept }} from "../../kit/studio";
import {{ type KitBeat, kitTiming }} from "../../kit/timing";
import EDIT from "./edit.json";

const DOC = EDIT as unknown as EditDoc;

export const CONCEPTS: ConceptBeat<KitBeat>[] = DOC.segments.flatMap((seg) =>
  (["A", "B", "C"] as const).flatMap((option) => {{
    const c = seg.concepts[option];
    // concepts whose component is not built yet (kind not in the kit) have no preview
    return c?.kind && c.kind in kitTiming ? [{{ moment: seg.id, option, round: seg.round, beat: beatFromConcept(seg, c) as KitBeat }}] : [];
  }}),
);
"""

INDEX_TSX = """import React from "react";
import {{ Composition }} from "remotion";
import {{ Edit }} from "./Edit";
import {{ SOURCE }} from "./source";

// The composition is exactly as long as the source footage, at the approved frame rate.
export const Composition_{ident}: React.FC = () => (
  <Composition
    id="{comp}"
    component={{Edit}}
    durationInFrames={{SOURCE.durationInFrames}}
    fps={{SOURCE.fps}}
    width={{SOURCE.width}}
    height={{SOURCE.height}}
    defaultProps={{{{ layers: "all" as const, concept: null }}}}
    calculateMetadata={{() => ({{ defaultCodec: "h264" as const, defaultOutName: "{slug}-picture.mp4" }})}}
  />
);
"""


def ident(slug):
    return slug.replace("-", "_")


def drop_links(pub: Path):
    """Remove the links in public/projects/<slug> (footage, proxy) themselves, never what they point to."""
    if not pub.is_dir() or pub.is_symlink():
        return
    for f in pub.iterdir():
        st = os.lstat(f)
        if f.is_symlink() or getattr(st, "st_reparse_tag", 0) == 0xA0000003:  # 0xA0000003: a Windows junction
            os.unlink(f)


def write_registry(app: Path):
    projects = sorted(d.name for d in (app / "src" / "projects").iterdir() if d.is_dir() and (d / "index.tsx").exists())
    lines = ["// GENERATED by the video-editing skill's edit_init.py: one <Composition> per",
             "// talking-head project in this folder. Do not edit by hand; re-run edit_init.py.",
             'import React from "react";']
    lines += [f'import {{ Composition_{ident(p)} }} from "./{p}";' for p in projects]
    body = "".join(f"\n    <Composition_{ident(p)} />" for p in projects)
    lines += ["", f"export const Projects: React.FC = () => (\n  <>{body}\n  </>\n);" if projects else "export const Projects: React.FC = () => <></>;", ""]
    (app / "src" / "projects" / "index.tsx").write_text("\n".join(lines))
    return projects


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("footage", nargs="?", help="the already-cut talking-head video (never modified)")
    ap.add_argument("--slug", required=True, help="project name: lowercase letters, digits, hyphens")
    ap.add_argument("--fps", type=float, help="approved delivery frame rate (default: the source's constant frame rate)")
    ap.add_argument("--fit", choices=["cover"], help="required when the source is not 9:16: centre-crop to fill 1080x1920 (needs user approval)")
    ap.add_argument("--app"); ap.add_argument("--work")
    ap.add_argument("--copy", action="store_true", help="copy the footage into public/ instead of linking (only if symlinks fail)")
    ap.add_argument("--remove", action="store_true", help="remove the Remotion project + link for --slug (never the original or work/)")
    ap.add_argument("--script-only", action="store_true", help="start without footage (timeline from --duration); attach the cut later")
    ap.add_argument("--duration", type=float, help="--script-only: timeline length in seconds (at least the end of the script)")
    a = ap.parse_args()

    if not V.SLUG_RE.match(a.slug):
        sys.exit("--slug must be lowercase letters, digits and hyphens (max 41 chars)")
    app = V.find_app(a.app)
    pdir = app / "src" / "projects" / a.slug
    pub = app / "public" / "projects" / a.slug

    if a.remove:
        shutil.rmtree(pdir, ignore_errors=True)
        drop_links(pub)
        shutil.rmtree(pub, ignore_errors=True)
        write_registry(app)
        print(f"removed Remotion project {a.slug} (src/projects + public link). The original footage and work/ are untouched.")
        return
    if a.script_only:
        return script_only(a, app, pdir)
    if not a.footage:
        sys.exit("footage path required (or --script-only --duration S)")

    src = Path(a.footage).expanduser().resolve()
    if not src.is_file():
        sys.exit(f"footage not found: {src}")
    info = V.probe(src)
    print(f"source: {src.name}  {info['width']}x{info['height']}  r={info['r_frame_rate']} avg={info['avg_frame_rate']}"
          f"  {info['duration']:.3f}s  audio={len(info['audio'])} stream(s)  rotation={info['rotation']}")

    problems = []
    if info["vfr"] and not a.fps:
        problems.append(f"variable frame rate (r={info['r_frame_rate']}, avg={info['avg_frame_rate']}): pass the approved --fps")
    fps = a.fps or info["fps"]
    if not fps or fps <= 0:
        problems.append("could not read the frame rate: pass --fps")
    aspect = info["width"] / info["height"]
    if abs(aspect - 9 / 16) > 0.01 and a.fit != "cover":
        problems.append(f"source is {info['width']}x{info['height']} (not 9:16): reframing must be approved; pass --fit cover for a centre crop")
    if not info["audio"]:
        problems.append("no audio stream: the dialogue must come with the cut")
    if problems:
        sys.exit("cannot start the project:\n  - " + "\n  - ".join(problems))

    fps = round(fps, 3)
    frames = int(round(info["duration"] * fps))
    sha = V.sha256(src)
    wd = V.work_dir(app, a.slug, a.work)
    for sub in ("frames", "plan", "sound", "renders", "qc"):
        (wd / sub).mkdir(parents=True, exist_ok=True)
    manifest_path = wd / "project.json"
    if manifest_path.exists():
        old = json.loads(manifest_path.read_text())
        if old["source"].get("sha256") and old["source"]["sha256"] != sha:
            sys.exit(f"{manifest_path} belongs to a different source file (sha256 differs). Use a new --slug.")

    # Remotion's file server refuses symlinked FILES but follows symlinked FOLDERS, and its bundler
    # forwards folder links instead of copying them: link the original's folder (read-only use),
    # so multi-GB footage is never copied. --copy copies the file instead (last resort).
    # Only the footage entry is replaced: the scene assets the user provided (public/projects/<slug>/assets) stay.
    drop_links(pub)
    if pub.is_symlink() or (pub.exists() and not pub.is_dir()):
        pub.unlink()
    shutil.rmtree(pub / "footage", ignore_errors=True)
    pub.mkdir(parents=True, exist_ok=True)
    if a.copy:
        (pub / "footage").mkdir()
        shutil.copy2(src, pub / "footage" / src.name)
    else:
        try:
            os.symlink(src.parent, pub / "footage", target_is_directory=True)
        except OSError as e:
            if os.name != "nt":
                raise
            # Windows allows symbolic links only with Developer Mode (or admin rights). A junction would not
            # help: Remotion re-creates every link in public/ as a symbolic link each time it bundles a render.
            sys.exit(f"Windows blocked the link to your video's folder ({e.strerror or e}).\n"
                     "Turn on Developer Mode once: Settings > System > For developers > Developer Mode (On), then import again.\n"
                     "(Or re-run with --copy to copy the video into the app instead.)")
    rel = f"projects/{a.slug}/footage/{src.name}"
    link = pub / "footage" / src.name

    pdir.mkdir(parents=True, exist_ok=True)
    (pdir / "source.ts").write_text(SOURCE_TS.format(src=json.dumps(rel), sw=info["width"], sh=info["height"], sfps=round(info["fps"] or fps, 6),
                                                      dur=round(info["duration"], 6), fps=fps, frames=frames, sha=sha, extra=""))
    # the single project document (Studio + Player + renderers + scripts)
    doc_path = pdir / "edit.json"
    src_info = {"src": rel, "sourceWidth": info["width"], "sourceHeight": info["height"], "sourceFps": round(info["fps"] or fps, 6),
                "sourceDurationSeconds": round(info["duration"], 6), "fps": fps, "durationInFrames": frames, "width": 1080, "height": 1920,
                "sha256": sha}
    if doc_path.exists():
        doc = V.load_doc(app, a.slug)
        was_script_only = doc["source"].get("scriptOnly")
        doc["source"] = src_info
        if was_script_only:
            ends = [x["end"] for x in doc["transcript"]["segments"] if x.get("end") is not None] + [b["at"] for b in doc["beats"]]
            if ends and max(ends) > info["duration"] + 0.05:
                print(f"WARN  the script / timeline reaches {max(ends):.2f} s but the attached cut is {info['duration']:.2f} s long: check the timestamps")
            print("attached the cut to the script-only project (script, segments, decisions and animations kept)")
        V.save_doc(app, a.slug, doc)
    else:
        doc_path.write_text(json.dumps(new_doc(a.slug, src_info), indent=1, ensure_ascii=False) + "\n")
    write_project_files(app, a.slug, pdir)
    projects = write_registry(app)

    manifest = {
        "slug": a.slug,
        "created": datetime.datetime.now().isoformat(timespec="seconds"),
        "source": {"path": str(src), "sha256": sha, "size": src.stat().st_size, "mtime_ns": src.stat().st_mtime_ns, "probe": info},
        "approved": {"fps": fps, "fps_from": "user" if a.fps else "source", "width": 1080, "height": 1920,
                     "fit": a.fit or "native 9:16", "durationInFrames": frames, "duration": frames / fps},
        "remotion": {"app": str(app), "composition": V.comp_id(a.slug), "project_dir": str(pdir), "public_src": rel,
                     "linked": "copy" if a.copy else "symlink"},
        "work": str(wd),
    }
    manifest_path.write_text(json.dumps(manifest, indent=1))
    drift = frames / fps - info["duration"]
    print(f"approved: 1080x1920 @ {fps} fps ({manifest['approved']['fps_from']}), {frames} frames "
          f"(timeline {frames / fps:.4f}s vs source {info['duration']:.4f}s, {drift * 1000:+.1f} ms)")
    if info["vfr"]:
        print("NOTE: variable-frame-rate source - Remotion samples it by time at the approved rate; the original is untouched.")
    if a.fit == "cover":
        print("NOTE: --fit cover centre-crops the source to 9:16 (approved reframe).")
    print(f"linked  public/{rel} -> {src} ({manifest['remotion']['linked']}; resolves: {link.resolve() == src})")
    print(f"project src/projects/{a.slug}/ (edit.json + source.ts written; beats.ts, Edit.tsx... kept if present)")
    print(f"studio  composition {V.comp_id(a.slug)} ({len(projects)} project(s) registered)")
    print(f"work    {wd}  (manifest: project.json)")
    # Creative Director workflow: CREATIVE-LOG.md, generated from edit.json
    import subprocess
    r = subprocess.run([sys.executable, str(Path(__file__).with_name("edit_decisions.py")), "init", a.slug, "--app", str(app)]
                       + (["--work", a.work] if a.work else []), capture_output=True, text=True)
    print("log     " + (r.stdout.strip() or r.stderr.strip()))


def new_doc(slug, src_info):
    return {"version": 1, "slug": slug, "rev": 0, "source": src_info, "transcript": {"origin": "none", "segments": []}, "segments": [],
            "beats": [], "sfx": [], "focus": [], "hookEnd": None, "approvals": [], "feedback": [], "keepVisible": [],
            "requests": [], "nextRequest": 1}


def write_project_files(app, slug, pdir):
    for name, text in (("beats.ts", BEATS_TS.format(slug=slug)), ("concepts.ts", CONCEPTS_TS.format(slug=slug)), ("sound-preview.ts", SOUND_TS),
                       ("Edit.tsx", EDIT_TSX.format(slug=slug)),
                       ("index.tsx", INDEX_TSX.format(ident=ident(slug), comp=V.comp_id(slug), slug=slug))):
        if not (pdir / name).exists():
            (pdir / name).write_text(text)


def script_only(a, app, pdir):
    """A project without footage: the user's script and the creative work can start before the cut is ready."""
    if a.footage:
        sys.exit("--script-only takes no footage (attach it later with: edit_init.py <footage> --slug ...)")
    if not a.duration or a.duration <= 0:
        sys.exit("--script-only needs --duration (seconds; at least the end of your script)")
    if (pdir / "edit.json").exists():
        sys.exit(f"project {a.slug} already exists")
    fps = round(a.fps or 30.0, 3)
    frames = int(round(a.duration * fps))
    src_info = {"src": "", "sourceWidth": 1080, "sourceHeight": 1920, "sourceFps": fps, "sourceDurationSeconds": round(frames / fps, 6), "fps": fps,
                "durationInFrames": frames, "width": 1080, "height": 1920, "sha256": "", "scriptOnly": True}
    wd = V.work_dir(app, a.slug, a.work)
    for sub in ("frames", "plan", "sound", "renders", "qc", "previews"):
        (wd / sub).mkdir(parents=True, exist_ok=True)
    pdir.mkdir(parents=True, exist_ok=True)
    (pdir / "source.ts").write_text(SOURCE_TS.format(src='""', sw=1080, sh=1920, sfps=fps, dur=src_info["sourceDurationSeconds"], fps=fps, frames=frames,
                                                      sha="", extra="\n  scriptOnly: true,"))
    (pdir / "edit.json").write_text(json.dumps(new_doc(a.slug, src_info), indent=1, ensure_ascii=False) + "\n")
    write_project_files(app, a.slug, pdir)
    write_registry(app)
    manifest = {"slug": a.slug, "created": datetime.datetime.now().isoformat(timespec="seconds"),
                "source": {"path": None, "sha256": None, "scriptOnly": True},
                "approved": {"fps": fps, "fps_from": "user" if a.fps else "default", "width": 1080, "height": 1920, "fit": "none (script-only)",
                             "durationInFrames": frames, "duration": frames / fps},
                "remotion": {"app": str(app), "composition": V.comp_id(a.slug), "project_dir": str(pdir), "public_src": "", "linked": "none"},
                "work": str(wd)}
    (wd / "project.json").write_text(json.dumps(manifest, indent=1))
    print(f"script-only project {a.slug}: {frames} frames @ {fps} fps ({frames / fps:.2f} s), no footage yet")
    print(f"attach the cut later: python3 scripts/edit_init.py /path/to/my-cut.mp4 --slug {a.slug}")
    import subprocess
    r = subprocess.run([sys.executable, str(Path(__file__).with_name("edit_decisions.py")), "init", a.slug, "--app", str(app)], capture_output=True, text=True)
    print("log     " + (r.stdout.strip() or r.stderr.strip()))


if __name__ == "__main__":
    main()
