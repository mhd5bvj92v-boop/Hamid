#!/usr/bin/env python3
"""Regenerate the human-readable library from data/references.json.

Outputs (all generated - edit the JSON, not these):
  references/library/INDEX.md         one-line-per-reference searchable index
  references/library/{ONS,TXT,FUL}.md full entries, observed vs inferred
  references/library/FAMILIES.md      references grouped by style family
  references/library/SOURCES.md       every original file -> reference ID (primary or alternate)
  assets/contact-sheets/*.png         labelled thumbnails for fast visual browsing

Usage: python3 scripts/build_library.py [--no-sheets]
"""
import sys
from collections import defaultdict
from pathlib import Path

import vvlib as V

HEADER = "<!-- GENERATED by scripts/build_library.py from data/references.json. Do not edit by hand. -->\n\n"


def rel_from_library(path: str) -> str:
    return "../../" + path.replace(" ", "%20")


def write_index(cat):
    refs = cat["references"]
    lines = [HEADER, "# Reference Index\n\n",
             f"{len(refs)} references "
             + ", ".join(f"{sum(r['category']==c for r in refs)} {c}" for c in V.CATEGORIES)
             + f" ({sum(len(r['alternates']) for r in refs)} alternate copies preserved).\n\n",
             "Search: `python3 scripts/search.py <words> [--cat ONS|TXT|FUL] [--family F] [--show ID]`, "
             "or grep this file. Open the image at `file` with the Read tool before designing from a reference.\n\n"]
    for c, label in V.CATEGORIES.items():
        lines.append(f"## {c} - {label}\n\n| ID | Title | Subcategory | Family | Also | Tags | File |\n|---|---|---|---|---|---|---|\n")
        for r in refs:
            if r["category"] != c:
                continue
            lines.append("| {id} | {title} | {sub} | {fam} | {also} | {tags} | `{file}` |\n".format(
                id=r["id"], title=r["title"].replace("|", "/"), sub=r["subcategory"], fam=r["family"],
                also=",".join(r.get("also_useful_for", [])) or "-", tags=", ".join(r["tags"]), file=r["file"]))
        lines.append("\n")
    (V.LIBRARY_DOCS / "INDEX.md").write_text("".join(lines), encoding="utf-8")


def entry_md(r):
    o, i = r["observed"], r["inferred"]
    pal = "  ".join(f"`{p['hex']}` {p['share_pct']}%" for p in o["palette"])
    alts = "".join(f"\n  - `{a['file']}` (original `{a['original_path']}`, {a['size'][0]}x{a['size'][1]}, {a['relation']}, distance {a['distance']})"
                   for a in r["alternates"]) or " none"
    return f"""### {r['id']} - {r['title']}

![{r['id']}]({rel_from_library(r['file'])})

- **Original file:** `{r['original_path']}` ({r['size'][0]}x{r['size'][1]} px, source folder: {r['source_folder']}, {r['batch']})
- **Category / subcategory:** {r['category']} / {r['subcategory']}. **Style family:** {r['family']}. **Also useful for:** {', '.join(r.get('also_useful_for', [])) or '-'}
- **Tags:** {', '.join(r['tags'])}
- **Alternate copies:**{alts}

**Observed (visible in the image)**
- **Visual description:** {o['description']}
- **Typography:** {o['typography']}
- **Colour palette (measured, dominant first):** {pal}
- **Composition:** {o['composition']}
- **Lighting & effects:** {o['lighting_effects']}
- **Depth & layering:** {o['depth_layering']}

**Inferred (creative interpretation - not visible in a still)**
- **Animation behaviour:** {i['animation']}
- **Suitable use cases:** {i['use_cases']}
- **Technical recreation:** {i['recreation']}
""" + (f"\n> Note: {r['notes']}\n" if r.get("notes") else "") + "\n---\n\n"


def write_category_docs(cat):
    for c, label in V.CATEGORIES.items():
        refs = [r for r in cat["references"] if r["category"] == c]
        out = [HEADER, f"# {c} - {label}\n\n{len(refs)} references. Palette values are measured from the image; "
               "animation/use/recreation are inferred from a still and must be treated as proposals.\n\n"]
        out += [entry_md(r) for r in refs]
        (V.LIBRARY_DOCS / f"{c}.md").write_text("".join(out), encoding="utf-8")


def write_families(cat):
    fam = defaultdict(list)
    for r in cat["references"]:
        fam[r["family"]].append(r)
    out = [HEADER, "# References by Style Family\n\nFamily recipes live in `references/design-language.md`.\n\n"]
    for f in sorted(fam):
        out.append(f"## {f} ({len(fam[f])})\n\n")
        out += [f"- {r['id']} - {r['title']} ({r['category']}/{r['subcategory']})\n" for r in fam[f]]
        out.append("\n")
    (V.LIBRARY_DOCS / "FAMILIES.md").write_text("".join(out), encoding="utf-8")


def write_sources(cat):
    rows = []
    for r in cat["references"]:
        rows.append((r["original_path"], r["id"], "primary", r["file"]))
        rows += [(a["original_path"], r["id"], "alternate", a["file"]) for a in r.get("alternates", [])]
    rows.sort()
    out = [HEADER, "# Source Manifest\n\nEvery original file received, and where it lives in the library. "
           f"{len(rows)} files: {sum(x[2]=='primary' for x in rows)} primary references, "
           f"{sum(x[2]=='alternate' for x in rows)} alternates (same design at another size/crop).\n\n"
           "| Original path | Reference | Role | Library file |\n|---|---|---|---|\n"]
    out += [f"| `{o}` | {i} | {role} | `{f}` |\n" for o, i, role, f in rows]
    (V.LIBRARY_DOCS / "SOURCES.md").write_text("".join(out), encoding="utf-8")


def write_sheets(cat, per=20, cols=5, tile=300):
    from PIL import Image, ImageDraw, ImageFont
    V.SHEETS_DIR.mkdir(parents=True, exist_ok=True)
    for old in V.SHEETS_DIR.glob("*.png"):
        old.unlink()
    font = None
    for cand in ["/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", "/System/Library/Fonts/Helvetica.ttc"]:
        try:
            font = ImageFont.truetype(cand, 13); break
        except OSError:
            pass
    font = font or ImageFont.load_default()
    for c in V.CATEGORIES:
        refs = [r for r in cat["references"] if r["category"] == c]
        for s in range(0, len(refs), per):
            chunk = refs[s:s + per]
            rows = (len(chunk) + cols - 1) // cols
            sheet = Image.new("RGB", (cols * tile, rows * (tile + 22)), (90, 90, 90))
            dr = ImageDraw.Draw(sheet)
            for k, r in enumerate(chunk):
                im = Image.open(V.SKILL_ROOT / r["file"]).convert("RGB")
                sc = min(tile / im.width, tile / im.height)
                im = im.resize((max(1, int(im.width * sc)), max(1, int(im.height * sc))), Image.LANCZOS)
                x, y = (k % cols) * tile, (k // cols) * (tile + 22)
                sheet.paste(im, (x + (tile - im.width) // 2, y + 22 + (tile - im.height) // 2))
                dr.rectangle([x, y, x + tile - 1, y + 21], fill=(0, 0, 0))
                dr.text((x + 4, y + 3), f"{r['id']} {r['title'][:28]}", fill=(255, 230, 0), font=font)
            sheet.save(V.SHEETS_DIR / f"{c}-{s // per + 1:02d}.png")


def main():
    cat = V.load_catalog()
    V.LIBRARY_DOCS.mkdir(parents=True, exist_ok=True)
    write_index(cat); write_category_docs(cat); write_families(cat); write_sources(cat)
    if "--no-sheets" not in sys.argv:
        write_sheets(cat)
    print(f"Built library for {len(cat['references'])} references.")


if __name__ == "__main__":
    main()
